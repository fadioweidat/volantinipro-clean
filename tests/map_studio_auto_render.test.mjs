// ── contratto sorgente: pane / z-order / casing ──────────────────────
test('MapStudioCanvas: 5 pane dedicati con z-order boundary < network < auto < manual < points', () => {
  for (const p of ['ms-boundary', 'ms-network', 'ms-auto', 'ms-manual', 'ms-points']) {
    assert.match(CANVAS, new RegExp(`<Pane name="${p}"`), `manca <Pane name="${p}">`);
  }
  const z = CANVAS.match(/PANE_Z = \{[^}]*\}/)[0];
  const val = (k) => Number(new RegExp(`${k}:\\s*(\\d+)`).exec(z)[1]);
  assert.ok(val('boundary') < val('network'));
  assert.ok(val('network') < val('auto'));
  assert.ok(val('auto') < val('manual'));
  assert.ok(val('manual') < val('points'));
});

