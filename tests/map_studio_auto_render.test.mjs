// ── comportamento: due operatori con automatico coesistono ──────────
function Harness({ apiRef, seed }) { apiRef.current = useMapStudioProject(seed); return null; }
function mount(seed) { const r = { current: null }; act(() => { TestRenderer.create(React.createElement(Harness, { apiRef: r, seed })); }); return r; }

const line = (a, b) => [[45.6 + a * 0.001, 9.14], [45.6 + a * 0.001, 9.15], [45.6 + b * 0.001, 9.16]];

test('T7 — genera op4 poi op1: entrambe le coperture automatiche coesistono, colori distinti', () => {
  const [op1, op2, op3, op4] = [0, 1, 2, 3].map((i) => createOperator({ index: i, name: `Operatore ${i + 1}` }));
  const seed = createProject({ name: 'Seveso', municipality: 'Seveso', operators: [op1, op2, op3, op4] });
  const api = mount(seed);

  // "genera" op4 (simula ciò che fa handleGenerate)
  act(() => {
    api.current.ops.clearFeatures((f) => f.source === 'auto' && f.operatorId === op4.id);
    api.current.ops.addFeatures([0, 1, 2].map((k) => ({ operatorId: op4.id, type: 'line', source: 'auto', style: { color: op4.color }, geometry: line(k, k + 1) })), 'auto');
  });
  assert.equal(api.current.project.features.filter((f) => f.source === 'auto').length, 3);

  // "genera" op1
  act(() => {
    api.current.ops.clearFeatures((f) => f.source === 'auto' && f.operatorId === op1.id);
    api.current.ops.addFeatures([0, 1].map((k) => ({ operatorId: op1.id, type: 'line', source: 'auto', style: { color: op1.color }, geometry: line(k + 5, k + 6) })), 'auto');
  });
  const auto = api.current.project.features.filter((f) => f.source === 'auto');
  assert.equal(auto.length, 5, 'op4 (3) + op1 (2) coesistono');
  assert.equal(auto.filter((f) => f.operatorId === op4.id).length, 3);
  assert.equal(auto.filter((f) => f.operatorId === op1.id).length, 2);
  assert.notEqual(op1.color, op4.color);
  assert.equal(auto.find((f) => f.operatorId === op4.id).style.color, op4.color);

  // RIGENERA op4 → sostituisce SOLO op4, op1 intatto, nessun duplicato
  act(() => {
    api.current.ops.clearFeatures((f) => f.source === 'auto' && f.operatorId === op4.id);
    api.current.ops.addFeatures([0, 1, 2, 3].map((k) => ({ operatorId: op4.id, type: 'line', source: 'auto', style: { color: op4.color }, geometry: line(k, k + 1) })), 'auto');
  });
  const auto2 = api.current.project.features.filter((f) => f.source === 'auto');
  assert.equal(auto2.filter((f) => f.operatorId === op4.id).length, 4, 'op4 rigenerato (4), non 3+4');
  assert.equal(auto2.filter((f) => f.operatorId === op1.id).length, 2, 'op1 intatto');
});

test('save/reload: le linee automatiche restano (source=auto, operatorId, style.color)', () => {
  const op = createOperator({ index: 0, name: 'A' });
  const seed = createProject({ name: 'Persist auto', municipality: 'Seveso', operators: [op] });
  const api = mount(seed);
  act(() => {
    api.current.ops.addFeatures([0, 1, 2].map((k) => ({ operatorId: op.id, type: 'line', source: 'auto', style: { color: op.color }, geometry: line(k, k + 1) })), 'auto');
  });
  let id;
  act(() => { id = api.current.persistence.save().project.id; });
  const back = loadProject(id);
  const auto = back.features.filter((f) => f.source === 'auto');
  assert.equal(auto.length, 3);
  assert.ok(auto.every((f) => f.operatorId === op.id));
  assert.ok(auto.every((f) => f.style && f.style.color === op.color));
});
